end


function [counts, probabilities] = calculateEmpiricalTransitions(T, states)
    sameSession = ...
        T.animalID(2:end) == T.animalID(1:end-1) & ...
        T.iOrig(2:end) == T.iOrig(1:end-1);
    from = T.stateMAP(1:end-1);
    to = T.stateMAP(2:end);
    from = from(sameSession);
    to = to(sameSession);
    [~,fromIndex] = ismember(from,states);
    [~,toIndex] = ismember(to,states);
    counts = accumarray([fromIndex,toIndex],1,[numel(states),numel(states)]);

    offDiagonalCounts = counts;
    offDiagonalCounts(1:numel(states)+1:end) = 0;
    rowTotals = sum(offDiagonalCounts,2);
    if any(rowTotals == 0)
        error('At least one state has no observed off-diagonal transitions.');
    end
    probabilities = offDiagonalCounts ./ rowTotals;
end


function fig = plotEmpiricalTransitions(probabilities)
    displayMatrix = probabilities;
    displayMatrix(1:4:end) = NaN;
    fig = figure('Color','w', 'Name','Figure S15L: empirical transitions');
    ax = axes(fig);
    imageHandle = imagesc(ax,displayMatrix,[0 1]);
    imageHandle.AlphaData = isfinite(displayMatrix);
    ax.Color = [0.65 0.65 0.65];
    axis(ax,'square');
    colormap(ax,parula(256));
    cb = colorbar(ax);
    cb.Label.String = 'Row-normalized p(transition)';
    xlabel(ax,'To state'); ylabel(ax,'From state');
    xticks(ax,1:3); yticks(ax,1:3);
    xticklabels(ax,string(1:3)); yticklabels(ax,string(1:3));
    styleAxes(ax);
end


function statsTable = compareStatesToOne( ...
        values, states, comparisons, deltaVariableName)
    nTests = size(comparisons,1);
    comparison = strings(nTests,1);
    medianDelta = nan(nTests,1);
    W = nan(nTests,1);
    nPairs = nan(nTests,1);
    nRanked = nan(nTests,1);
    pRaw = nan(nTests,1);
    for iTest = 1:nTests
        stateA = comparisons(iTest,1);
        stateB = comparisons(iTest,2);
        [pRaw(iTest),W(iTest),nPairs(iTest),nRanked(iTest), ...
            medianDelta(iTest)] = pairedSignrank( ...
            values(:,states == stateA), values(:,states == stateB));
        comparison(iTest) = sprintf('State %d vs State %d',stateA,stateB);
    end
    pHolm = holmAdjust(pRaw);
    statsTable = table(comparison,medianDelta,W,nPairs,nRanked,pRaw,pHolm, ...
        'VariableNames',{'comparison',deltaVariableName,'W', ...
        'N_pairs','N_ranked','p_raw','p_Holm'});
end


function [p,W,nPairs,nRanked,medianDelta] = pairedSignrank(a,b)
    keep = isfinite(a) & isfinite(b);
    a = a(keep);
    b = b(keep);
    delta = a - b;
    nPairs = numel(delta);
    nRanked = sum(delta ~= 0);
    medianDelta = median(delta,'omitnan');
    p = NaN;
    W = NaN;
    if nRanked > 0
        [p,~,signedRankStats] = signrank(a,b);
        W = signedRankStats.signedrank;
    end
end


function pAdjusted = holmAdjust(pRaw)
    pAdjusted = nan(size(pRaw));
    validIndices = find(isfinite(pRaw));
    if isempty(validIndices)
        return;
    end
    [pSorted,order] = sort(pRaw(validIndices));
    m = numel(pSorted);
    adjustedSorted = (m - (1:m)' + 1) .* pSorted(:);
    adjustedSorted = min(cummax(adjustedSorted),1);
    pAdjusted(validIndices(order)) = adjustedSorted;
end


function label = formatSubmittedPValue(p)
    if ~isfinite(p)
        label = "p = n.a.";
    elseif p < 1e-6
        label = "p < 10^{-6}*";
    elseif p < 1e-4
        label = "p < 10^{-4}*";
    elseif p < 0.05
        label = "p = " + string(sprintf('%.2f',p)) + "*";
    else
        label = "p = " + string(sprintf('%.2f',p));
    end
end


function tableOut = matrixToStateTable(matrix,states)
    tableOut = array2table(matrix, ...
        'VariableNames',compose('to_state_%d',states));
    tableOut.from_state = states;
    tableOut = movevars(tableOut,'from_state','Before',1);
end


function requireVariables(T,required,description)
    missing = setdiff(required,T.Properties.VariableNames,'stable');
    if ~isempty(missing)
        error('%s missing required variables: %s', ...
            description,strjoin(missing,', '));
    end
end


function assertUniqueRows(T,keys,description)
    [~,uniqueRows] = unique(T(:,keys),'rows','stable');
    if numel(uniqueRows) ~= height(T)
        error('%s contains duplicate key rows.',description);
    end
end


